#!/usr/bin/env python3
"""Write src/global_talents.h: the game's talents whose words reach further than their spell modifiers.

A Hero has every class's spells, and a talent saying "all your healing spells", "all spells" or "your Frost spells"
means it ("all means all"): the server makes its modifiers apply to every class's spells of that kind
(wildcard.cpp, titan_global_talents: GlobalScript::OnIsAffectedBySpellModCheck), not only its own class's.

Read from the client's Spell.dbc and Talent.dbc (the 3.3.5a originals): every talent rank spell with a spell
modifier (its effects' class masks) whose description says one of:
- healing: "healing spells", "all healing";
- spells: "all spells", "all of your spells", "your spells";
- a school: "your Frost spells", "your Fire damage", "your Shadow spells"... (Frost, Fire, Shadow, Nature, Arcane,
  Holy).
Usage: python3 global_talents.py <dir with Spell.dbc and Talent.dbc> <out header>
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / 'client-patch'))

import patch_spells as ps  # noqa: E402

SCHOOLS = {'Holy': 0x2, 'Fire': 0x4, 'Nature': 0x8, 'Frost': 0x10, 'Shadow': 0x20, 'Arcane': 0x40}
HEALING = re.compile(r'\bhealing spells\b|\ball healing\b', re.I)
SPELLS = re.compile(r'\ball (?:of )?(?:your )?spells\b|\byour spells\b', re.I)
SCHOOL = re.compile(r'\byour (Holy|Fire|Nature|Frost|Shadow|Arcane)(?: damage)?(?: spells| damage)\b')
KIND_HEALING, KIND_SPELLS, KIND_SCHOOL = 1, 2, 3
# Matched by their words, but their modifiers are for named spells (the "all healing" is a debuff on the target).
EXCLUDE = {'Grace', 'Improved Mind Blast'}


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    source, out = Path(sys.argv[1]), Path(sys.argv[2])
    spells = ps.Dbc(source / 'Spell.dbc', ps.SPELL_FIELDS)
    talents = ps.Dbc(source / 'Talent.dbc', ps.TALENT_FIELDS)
    rows = []
    for talent in talents.rows.values():
        ranks = [spell_id for spell_id in talent[4:9] if spell_id in spells.rows]
        if not ranks:
            continue
        first = spells.rows[ranks[0]]
        masked = any(first[ps.CLASS_MASK + effect * 3 + word] for effect in range(3) for word in range(3))
        if not masked:
            continue
        text = spells.string(first[ps.DESCRIPTION]) or ''
        name = spells.string(first[ps.NAME])
        if name in EXCLUDE:
            continue
        kind, school = 0, 0
        if HEALING.search(text):
            kind = KIND_HEALING
        elif SPELLS.search(text):
            kind = KIND_SPELLS
        elif match := SCHOOL.search(text):
            kind, school = KIND_SCHOOL, SCHOOLS[match.group(1)]
        if kind:
            rows += [(spell_id, kind, school, name) for spell_id in ranks]
    rows.sort()
    lines = ['// Generated by tools/wildcard/global_talents.py from the client\'s Spell.dbc and Talent.dbc: talents',
             '// whose words reach every class\'s spells of a kind (healing, every spell, a school). Do not edit by',
             '// hand.',
             '#ifndef MOD_TITAN_GLOBAL_TALENTS_H', '#define MOD_TITAN_GLOBAL_TALENTS_H', '', '#include "Define.h"', '',
             'namespace GlobalTalents', '{',
             '    enum Kind : uint8 { HEALING = 1, SPELLS = 2, SCHOOL = 3 };',
             '    struct Entry', '    {', '        uint32 SpellId;', '        uint8 Kind;',
             '        uint8 School;           // SpellSchoolMask, for SCHOOL', '    };', '',
             '    constexpr Entry ENTRIES[] = {']
    for spell_id, kind, school, name in rows:
        lines.append(f'        {{ {spell_id}, {kind}, 0x{school:02X} }},   // {name}')
    lines += ['    };', '}', '', '#endif', '']
    out.write_text('\n'.join(lines))
    print(f'Wrote {out}: {len(rows)} rank spells, {len({r[3] for r in rows})} talents')


if __name__ == '__main__':
    main()
