#!/usr/bin/env python3
"""Write src/resource_talents.h: talents whose words name the resources they work with.

A talent only helps a Hero who uses what it talks about: "Energy", "Rage", "mana", "combo points", a pet's "Focus".
Many of them are dummy auras or procs the core scripts, so their data names no resource (Combat Potency, Seal Fate,
Energy Burst...), and Wildcard rolled them for any Hero: Energy talents for a caster. Their descriptions say it.

Read from the patched client's Spell.dbc and Talent.dbc (client-patch/patch_spells.py's output: our own talents
too, and Runic Power already turned into Rage): every talent's first rank, the resources its description names.
Wildcard (wildcard.cpp, GrantTalent) rolls such a talent only for a Hero using at least one of them.
Usage: python3 resource_talents.py <dir with Spell.dbc and Talent.dbc> <out header>
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / 'client-patch'))

import patch_spells as ps  # noqa: E402

POWER_MANA, POWER_RAGE, POWER_ENERGY = 0, 1, 3
COMBO_POINTS, PET_FOCUS = 1 << 30, 1 << 29
WORDS = [
    (re.compile(r'\bmana\b', re.I), 1 << POWER_MANA),
    (re.compile(r'\bRage\b'), 1 << POWER_RAGE),
    (re.compile(r'\bEnergy\b'), 1 << POWER_ENERGY),
    (re.compile(r'\bcombo points?\b', re.I), COMBO_POINTS),
    # A pet's Focus ("generate 25 Focus", "cost no Focus", "Focus regeneration"), not "Focus your gaze".
    (re.compile(r'(?:\d|\$\S*|\bno|\bof) Focus\b|\bFocus regeneration\b'), PET_FOCUS),
]


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    source, out = Path(sys.argv[1]), Path(sys.argv[2])
    spells = ps.Dbc(source / 'Spell.dbc', ps.SPELL_FIELDS)
    talents = ps.Dbc(source / 'Talent.dbc', ps.TALENT_FIELDS)
    rows = {}
    for talent in talents.rows.values():
        first_id = talent[4]
        first = spells.rows.get(first_id)
        if not first:
            continue
        text = spells.string(first[ps.DESCRIPTION]) or ''
        mask = 0
        for pattern, bit in WORDS:
            if pattern.search(text):
                mask |= bit
        if mask:
            rows[first_id] = (mask, spells.string(first[ps.NAME]))
    lines = ['// Generated by tools/wildcard/resource_talents.py from the patched client\'s Spell.dbc and Talent.dbc:',
             '// talents whose words name the resources they work with. Do not edit by hand.',
             '#ifndef MOD_TITAN_RESOURCE_TALENTS_H', '#define MOD_TITAN_RESOURCE_TALENTS_H', '', '#include "Define.h"',
             '', 'namespace ResourceTalents', '{',
             '    // 1 << a power type (mana, Rage, Energy), and these.',
             f'    constexpr uint32 COMBO_POINTS = 0x{COMBO_POINTS:08X};',
             f'    constexpr uint32 PET_FOCUS = 0x{PET_FOCUS:08X};', '',
             '    struct Entry', '    {', '        uint32 SpellId;     // the first rank', '        uint32 Uses;',
             '    };', '', '    constexpr Entry ENTRIES[] = {']
    for spell_id, (mask, name) in sorted(rows.items()):
        lines.append(f'        {{ {spell_id}, 0x{mask:08X} }},   // {name}')
    lines += ['    };', '}', '', '#endif', '']
    out.write_text('\n'.join(lines))
    print(f'Wrote {out}: {len(rows)} talents')


if __name__ == '__main__':
    main()
