#!/usr/bin/env python3
"""The Legendary Runes' own output, for src/rune_power.cpp: every spell of theirs (client-patch/patch_runes.py) that
deals damage, heals or shields, sorted into those three, so the server can scale each kind (RUNE_*_POWER there).

- damage: a School Damage effect, or a periodic damage aura;
- healing: a Heal effect, or a periodic heal aura;
- shields: a school absorb aura.

Writes src/rune_power.h. Run it again whenever patch_runes.py gains spells. Usage: python3 rune_power.py
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODULE = HERE.parents[1]
HEADER = MODULE / 'src' / 'rune_power.h'
sys.path.insert(0, str(MODULE / 'client-patch'))

import patch_runes  # noqa: E402

EFFECT_SCHOOL_DAMAGE, EFFECT_HEAL, EFFECT_APPLY_AURA = 2, 10, 6
AURA_PERIODIC_DAMAGE, AURA_PERIODIC_HEAL, AURA_SCHOOL_ABSORB = 3, 8, 69


def kinds():
    damage, healing, shields = set(), set(), set()
    for spell in patch_runes.SPELLS:
        if 93500 <= spell['id'] < 93600:      # the Fireforged effects': the gear's, not a rune's
            continue
        for effect in spell.get('effects', {}).values():
            kind, aura = effect.get('Effect'), effect.get('Aura')
            if kind == EFFECT_SCHOOL_DAMAGE or (kind == EFFECT_APPLY_AURA and aura == AURA_PERIODIC_DAMAGE):
                damage.add(spell['id'])
            elif kind == EFFECT_HEAL or (kind == EFFECT_APPLY_AURA and aura == AURA_PERIODIC_HEAL):
                healing.add(spell['id'])
            elif kind == EFFECT_APPLY_AURA and aura == AURA_SCHOOL_ABSORB:
                shields.add(spell['id'])
    return sorted(damage), sorted(healing), sorted(shields)


def block(name, ids):
    lines = [f'    constexpr uint32 {name}[] = {{']
    row = []
    for spell_id in ids:
        row.append(str(spell_id))
        if len(row) == 12:
            lines.append('        ' + ', '.join(row) + ',')
            row = []
    if row:
        lines.append('        ' + ', '.join(row) + ',')
    lines.append('    };')
    return lines


def main():
    damage, healing, shields = kinds()
    lines = [
        '// Generated by tools/runes/rune_power.py: the Legendary Runes\' own damage, healing and shield spells',
        '// (client-patch/patch_runes.py), for src/rune_power.cpp. Do not edit.',
        '#ifndef MOD_TITAN_RUNE_POWER_H',
        '#define MOD_TITAN_RUNE_POWER_H',
        '',
        '#include "Define.h"',
        '',
        'namespace RunePower',
        '{',
        *block('DAMAGE', damage),
        *block('HEALING', healing),
        *block('SHIELDS', shields),
        '}',
        '',
        '#endif',
        '',
    ]
    HEADER.write_text('\n'.join(lines))
    print(f'{len(damage)} damage, {len(healing)} healing, {len(shields)} shield spells: {HEADER.name}')


if __name__ == '__main__':
    main()
