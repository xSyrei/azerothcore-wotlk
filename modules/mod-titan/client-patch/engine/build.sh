#!/bin/sh
# Builds the Emberforge Engine (dist/Emberforge-d3d9.dll; the launcher puts it in the game folder as d3d9.dll) with
# MinGW-w64:   apt-get install g++-mingw-w64-i686    then    sh build.sh
# Generates src/forward.h (tools/gen_forward.py: the Direct3D 9 pass-through classes) and src/known_shaders.h (the water
# shaders' fingerprints, from hd/psLiquidProcWater*.asm). With D3DCOMPILER set (a 64-bit d3dcompiler_47.dll) and Wine,
# it compiles src/*.hlsl to src/shaders.h too (tools/compile_shaders.sh); otherwise the committed shaders.h is used.
set -e
cd "$(dirname "$0")"
if [ -n "$D3DCOMPILER" ]; then
    sh tools/compile_shaders.sh
fi
python3 tools/gen_forward.py > src/forward.h
python3 - <<'PY'
import sys
sys.path.insert(0, '../hd')
import d3d9asm
shader = open('../hd/psLiquidProcWater.asm').read()
data = shader.split('; --- tail:')[0] + open('../hd/psLiquidProcWater_data.asm').read()
def fnv(b):
    h = 2166136261
    for x in b:
        h = ((h ^ x) * 16777619) & 0xFFFFFFFF
    return h
with open('src/known_shaders.h', 'w') as f:
    f.write('// Generated by build.sh: FNV-1a of the water shaders\' bytecode (hd/psLiquidProcWater*.asm).\n')
    f.write('#pragma once\n#include <cstdint>\n')
    f.write('constexpr uint32_t kWaterShader = 0x%08x;        // patch-enUS-7\n' % fnv(d3d9asm.assemble(shader)))
    f.write('constexpr uint32_t kWaterShaderReShade = 0x%08x; // Water-ReShade.MPQ\n' % fnv(d3d9asm.assemble(data)))
PY
mkdir -p ../dist
I=third_party/imgui
i686-w64-mingw32-g++ -std=c++17 -O2 -s -shared -static -static-libgcc -static-libstdc++ \
    -I$I -Isrc -DIMGUI_DISABLE_OBSOLETE_FUNCTIONS -Wall -Wno-unknown-pragmas -Wno-missing-field-initializers \
    -o ../dist/Emberforge-d3d9.dll src/engine.cpp \
    $I/imgui.cpp $I/imgui_draw.cpp $I/imgui_tables.cpp $I/imgui_widgets.cpp \
    $I/backends/imgui_impl_dx9.cpp $I/backends/imgui_impl_win32.cpp \
    -luser32 -lgdi32 -ldwmapi -luuid -Wl,--kill-at
echo "Wrote $(cd ../dist && pwd)/Emberforge-d3d9.dll"
