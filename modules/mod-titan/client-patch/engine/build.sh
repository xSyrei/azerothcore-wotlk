#!/bin/sh
# Builds the Emberforge Engine (Emberforge.addon32, a ReShade add-on: a 32-bit Windows DLL) with MinGW-w64:
#   apt-get install g++-mingw-w64-i686    then    sh build.sh
# Output: ../dist/Emberforge.addon32. The water shaders' fingerprints come from hd/psLiquidProcWater*.asm.
set -e
cd "$(dirname "$0")"
python3 - <<'PY'
import sys
sys.path.insert(0, '../hd')
import d3d9asm
shader = open('../hd/psLiquidProcWater.asm').read()
data = shader.split('; --- tail:')[0] + open('../hd/psLiquidProcWater_data.asm').read()
def fnv(b):
    h = 2166136261
    for x in b:
        h = ((h ^ x) * 16777619) & 0xFFFFFFFF
    return h
with open('src/known_shaders.h', 'w') as f:
    f.write('// Generated by build.sh: FNV-1a of the water shaders\' bytecode (hd/psLiquidProcWater*.asm).\n')
    f.write('#pragma once\n')
    f.write('constexpr uint32_t kWaterShader = 0x%08x;        // patch-enUS-7\n' % fnv(d3d9asm.assemble(shader)))
    f.write('constexpr uint32_t kWaterShaderReShade = 0x%08x; // Water-ReShade.MPQ\n' % fnv(d3d9asm.assemble(data)))
PY
mkdir -p ../dist
i686-w64-mingw32-g++ -std=c++17 -O2 -s -shared -static -static-libgcc -static-libstdc++ \
    -Ithird_party/reshade/include -Ithird_party/imgui -Isrc -Isrc/compat \
    -Wall -Wno-unknown-pragmas -Wno-missing-field-initializers -Wno-attributes \
    -o ../dist/Emberforge.addon32 src/emberforge.cpp -Wl,--kill-at
echo "Wrote $(cd ../dist && pwd)/Emberforge.addon32"
