#!/usr/bin/env python3
"""Generates src/forward.h: classes implementing IDirect3D9 and IDirect3DDevice9 by passing every call to the real
object, from MinGW's d3d9.h (the engine's own classes derive from them and override the calls they watch).

Usage: python3 gen_forward.py [path to d3d9.h] > ../src/forward.h
"""
import re
import sys

HEADER = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/mingw-w64/include/d3d9.h'


def methods(text, interface):
    start = text.index(f'DECLARE_INTERFACE_({interface},')
    body = ' '.join(text[start:text.index('};', start)].split())     # declarations may span lines
    out = []
    for m in re.finditer(r'STDMETHOD(_)?\((?:([^,()]+),\s*)?(\w+)\)\s*\(THIS_?\s*(.*?)\)\s*PURE;', body):
        ret = (m.group(2) or 'HRESULT').strip()
        name = m.group(3)
        params = m.group(4).strip()
        names, typed = [], []
        if params:
            for i, p in enumerate(params.split(',')):
                p = p.strip()
                words = re.findall(r'\w+', re.sub(r'\[.*?\]', '', p))
                unnamed = (p.endswith('*') or len(words) == 1
                           or (len(words) == 2 and words[0] in ('const', 'CONST', 'struct')))
                if unnamed:                         # some declarations leave the parameter unnamed
                    names.append(f'a{i}')
                    typed.append(f'{p} a{i}')
                else:
                    names.append(words[-1])
                    typed.append(p)
        out.append((ret, name, ', '.join(typed), names))
    return out


def emit(cls, interface, ms, trace=False):
    """trace: each call and its result go to EngineTrace (the engine's log), for the few calls made at start-up."""
    lines = [f'class {cls} : public {interface}', '{', 'protected:', f'    {interface} *real;', '', 'public:',
             f'    explicit {cls}({interface} *r) : real(r) {{}}', f'    virtual ~{cls}() = default;']
    for ret, name, params, names in ms:
        lines.append(f'    {ret} STDMETHODCALLTYPE {name}({params}) override')
        call = f'real->{name}({", ".join(names)})'
        if trace:
            lines.append(f'    {{ {ret} r = {call}; EngineTrace("{interface}::{name}", (unsigned long)(uintptr_t)r); '
                         'return r; }')
        else:
            lines.append(f'    {{ return {call}; }}')
    lines.append('};')
    return '\n'.join(lines)


text = open(HEADER).read()
print('// Generated by tools/gen_forward.py from MinGW\'s d3d9.h: every call passed to the real object.')
print('#pragma once\n#include <cstdint>\n#include <d3d9.h>\n')
print('void EngineTrace(const char *call, unsigned long result);\n')
print(emit('Direct3D9Forward', 'IDirect3D9', methods(text, 'IDirect3D9'), trace=True))
print()
print(emit('Device9Forward', 'IDirect3DDevice9', methods(text, 'IDirect3DDevice9')))
print()
print(emit('SwapChain9Forward', 'IDirect3DSwapChain9', methods(text, 'IDirect3DSwapChain9')))
