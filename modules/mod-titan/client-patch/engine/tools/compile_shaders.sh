#!/bin/sh
# Compiles the engine's shaders (src/*.hlsl, ps_3_0) to src/shaders.h with Microsoft's compiler: d3dcompiler_47.dll
# (64-bit; one ships with every Electron app, the launcher's included) run under Wine. Wine's own compiler cannot
# build shader model 3. Usage: D3DCOMPILER=/path/to/d3dcompiler_47.dll sh tools/compile_shaders.sh
set -e
cd "$(dirname "$0")/.."
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cp "$D3DCOMPILER" "$work/d3dcompiler_47.dll"
x86_64-w64-mingw32-gcc -O2 tools/fxc.c -o "$work/fxc.exe"
for name in water distance; do
    cp "src/$name.hlsl" "$work/"
    (cd "$work" && WINEDEBUG=-all wine fxc.exe "$name.hlsl" main ps_3_0 "$name.bin" > "$name.log") || {
        cat "$work/$name.log"
        exit 1
    }
done
python3 - "$work" > src/shaders.h <<'PY'
import sys
print('// Generated by tools/compile_shaders.sh from src/*.hlsl (ps_3_0): the engine\'s shaders\' bytecode.')
print('#pragma once')
for name in ('water', 'distance'):
    data = open(f'{sys.argv[1]}/{name}.bin', 'rb').read()
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    print(f'static const DWORD k{name.capitalize()}PixelShader[] = {{')
    for i in range(0, len(words), 8):
        print('    ' + ', '.join(f'0x{w:08x}' for w in words[i:i + 8]) + ',')
    print('};')
PY
echo "Wrote src/shaders.h"
