#!/usr/bin/env python3
"""EmberforgeSpellClasses.lua: which class every class spell belongs to, for the spellbook's class tabs.

The patched SpellBookFrame.lua (FrameXML/) files a Hero's spells under one tab per class. It looks each
spell up in EMBERFORGE_SPELL_CLASSES (spell id -> class token), made here from the game's own data: every
spell of a class's skill lines in SkillLineAbility.dbc (each spec's, and Runeforging), and the Demon
Hunter's spells of our own (patch_spells.py).
"""

import struct
from pathlib import Path

# Each class's skill lines (SkillLine.dbc, category Class): its three specs (and the Death Knight's Runeforging).
CLASS_SKILL_LINES = {
    'WARRIOR': (26, 256, 257), 'PALADIN': (594, 267, 184), 'HUNTER': (50, 163, 51),
    'ROGUE': (253, 38, 39), 'PRIEST': (613, 56, 78), 'DEATHKNIGHT': (770, 771, 772, 776),
    'SHAMAN': (375, 373, 374), 'MAGE': (237, 8, 6), 'WARLOCK': (355, 354, 593), 'DRUID': (574, 134, 573),
}
SKILL_LINE_ABILITY_FIELDS = 14
SKILL_LINE, SPELL = 1, 2


def build(dbc_dir, own_spells):
    """The Lua file's text: own_spells are the Demon Hunter's spell ids."""
    data = (Path(dbc_dir) / 'SkillLineAbility.dbc').read_bytes()
    _, count, fields, record_size, _ = struct.unpack_from('<4s4I', data)
    assert fields == SKILL_LINE_ABILITY_FIELDS, 'not a 3.3.5a SkillLineAbility.dbc'
    class_of_skill = {skill: token for token, skills in CLASS_SKILL_LINES.items() for skill in skills}
    classes = {}
    for i in range(count):
        row = struct.unpack_from(f'<{fields}I', data, 20 + i * record_size)
        if row[SKILL_LINE] in class_of_skill:
            classes.setdefault(row[SPELL], class_of_skill[row[SKILL_LINE]])
    for spell_id in own_spells:
        classes[spell_id] = 'DEMONHUNTER'
    lines = ['-- Generated by client-patch/interface/spell_classes.py: spell id -> class, for the spellbook\'s',
             '-- class tabs (SpellBookFrame.lua). Do not edit.',
             'EMBERFORGE_SPELL_CLASSES = {']
    lines += [f'\t[{spell_id}] = "{token}",' for spell_id, token in sorted(classes.items())]
    lines.append('};')
    return '\n'.join(lines) + '\n'
